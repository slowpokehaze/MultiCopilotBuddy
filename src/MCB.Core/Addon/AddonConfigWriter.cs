using System.Text;
using MCB.Core.Models;
using MCB.Core.Storage;

namespace MCB.Core.Addon;

/// <summary>
/// Генератор Interface\AddOns\MCBuddy\Config.lua перед запуском клиента
/// (план §4.2, как в WowManager): рорстер для окна/меню в игре, цвета классов,
/// флаги (hoverCard/minimap/syncFriends/lfg/harvest). Записывается при каждом
/// запуске — ручные правки не сохраняются by design.
/// </summary>
public static class AddonConfigWriter
{
    /// <summary>Цвет класса (HEX без #) — как в таблице классов WoW (RAID_CLASS_COLORS).</summary>
    private static readonly Dictionary<string, string> ClassColors = new(StringComparer.OrdinalIgnoreCase)
    {
        ["WARRIOR"] = "C79C6E", ["PALADIN"] = "F58CBA", ["HUNTER"] = "ABD473",
        ["ROGUE"] = "FFF569", ["PRIEST"] = "FFFFFF", ["DEATHKNIGHT"] = "C41F3B",
        ["SHAMAN"] = "0070DE", ["MAGE"] = "69CCF0", ["WARLOCK"] = "9482C9",
        ["MONK"] = "00FF96", ["DRUID"] = "FF7D0A",
    };

    public static string ConfigPath(string wowDirectory)
        => Path.Combine(wowDirectory, "Interface", "AddOns", "MCBuddy", "Config.lua");

    public static void Write(string wowDirectory, MultiAccountStore store, AccountModel account,
        IEnumerable<string>? harvestChars = null, bool? lfg = null, bool? syncFriends = null)
    {
        var sb = new StringBuilder();
        sb.AppendLine("-- Generated by Multi Copilot Buddy before launch. Do not edit.");
        sb.AppendLine("MCBuddyConfig = {");
        sb.AppendLine("  currentAccount = \"" + LuaEscape(account.Login) + "\",");
        sb.AppendLine("  characters = {");

        foreach (var character in account.Characters.Where(c => !c.Hidden).OrderBy(c => c.Order))
        {
            var color = ClassColors.TryGetValue(character.Class, out var hex) ? hex : "FFFFFF";
            var level = character.Data.TryGetValue("level", out var levelText) ? levelText : "0";
            var gs = character.Data.TryGetValue("gs", out var gsText) ? gsText : "";
            var gold = ExtractGoldCopper(character);
            var realm = string.IsNullOrWhiteSpace(character.Realm) ? account.Realm : character.Realm;

            sb.Append("    { name=\"").Append(LuaEscape(character.Name))
              .Append("\", realm=\"").Append(LuaEscape(realm))
              .Append("\", account=\"").Append(LuaEscape(account.Login))
              .Append("\", isAccount=false, color=\"").Append(color)
              .Append("\", lvl=").Append(long.TryParse(level, out var lvl) ? lvl : 0);
            if (long.TryParse(gs, out var gsValue) && gsValue > 0)
            {
                sb.Append(", gs=").Append(gsValue);
            }

            if (gold > 0)
            {
                sb.Append(", gold=").Append(gold);
            }

            sb.AppendLine(" },");
        }

        sb.AppendLine("  },");
        sb.AppendLine("  hoverCard = true,");
        sb.AppendLine("  showMinimap = true,");
        sb.AppendLine("  syncFriends = " + ToLua(syncFriends ?? store.Config.Social.SyncFriends) + ",");
        sb.AppendLine("  lfg = " + ToLua(lfg ?? store.Config.Lfg.Enabled) + ",");
        sb.AppendLine("  harvest = " + ToLua(harvestChars is not null && harvestChars.Any()) + ",");
        sb.AppendLine("  harvestWait = 12,");
        sb.AppendLine("  harvestChars = { " + string.Join(", ", (harvestChars ?? Enumerable.Empty<string>()).Select(c => "\"" + LuaEscape(c) + "\"")) + " },");
        sb.AppendLine("}");

        var path = ConfigPath(wowDirectory);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, sb.ToString(), new UTF8Encoding(false));
    }

    /// <summary>gold в меди из Data["gold"] ("1234г 56с 78м") — для меню в игре.</summary>
    public static long ExtractGoldCopper(CharacterModel character)
    {
        if (!character.Data.TryGetValue("gold", out var text))
        {
            return 0;
        }

        long Parse(string suffix)
        {
            var match = System.Text.RegularExpressions.Regex.Match(text, @"(\d+)\s*" + suffix);
            return match.Success ? long.Parse(match.Groups[1].Value) : 0;
        }

        return Parse("г") * 10000 + Parse("с") * 100 + Parse("м");
    }

    private static string ToLua(bool value) => value ? "true" : "false";

    private static string LuaEscape(string value)
        => value.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n").Replace("\r", string.Empty);
}
